-- Steven Gao personal site CMS
-- Run this once in Supabase SQL Editor.

create table if not exists public.site_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'life' check (category in ('life','investing','engineering')),
  summary text not null default '',
  body text not null default '',
  published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  published_at timestamptz
);

create table if not exists public.site_settings (
  id text primary key default 'main',
  display_name text,
  legal_name text,
  hero_title text,
  hero_copy text,
  focus_title text,
  focus_body text,
  about_body text,
  location_text text,
  updated_at timestamptz not null default now()
);

alter table public.site_admins enable row level security;
alter table public.posts enable row level security;
alter table public.site_settings enable row level security;

create or replace function public.is_site_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists(select 1 from public.site_admins where user_id = auth.uid());
$$;

revoke all on function public.is_site_admin() from public;
grant execute on function public.is_site_admin() to anon, authenticated;

drop policy if exists "public can read published posts" on public.posts;
create policy "public can read published posts" on public.posts
for select to anon, authenticated
using (published = true or public.is_site_admin());

drop policy if exists "admins can insert posts" on public.posts;
create policy "admins can insert posts" on public.posts
for insert to authenticated with check (public.is_site_admin());

drop policy if exists "admins can update posts" on public.posts;
create policy "admins can update posts" on public.posts
for update to authenticated using (public.is_site_admin()) with check (public.is_site_admin());

drop policy if exists "admins can delete posts" on public.posts;
create policy "admins can delete posts" on public.posts
for delete to authenticated using (public.is_site_admin());

drop policy if exists "public can read settings" on public.site_settings;
create policy "public can read settings" on public.site_settings
for select to anon, authenticated using (true);

drop policy if exists "admins can insert settings" on public.site_settings;
create policy "admins can insert settings" on public.site_settings
for insert to authenticated with check (public.is_site_admin());

drop policy if exists "admins can update settings" on public.site_settings;
create policy "admins can update settings" on public.site_settings
for update to authenticated using (public.is_site_admin()) with check (public.is_site_admin());

grant select on public.posts to anon;
grant select,insert,update,delete on public.posts to authenticated;
grant usage,select on sequence public.posts_id_seq to authenticated;
grant select on public.site_settings to anon;
grant select,insert,update on public.site_settings to authenticated;
grant select on public.site_admins to authenticated;

